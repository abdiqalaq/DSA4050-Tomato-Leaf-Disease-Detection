
from pathlib import Path

import numpy as np
import pandas as pd
import streamlit as st
import tensorflow as tf
from PIL import Image
import plotly.express as px

# Project directories
ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "models"
RESULTS = ROOT / "results"

st.set_page_config(
    page_title="Tomato Leaf Disease Detection",
    page_icon="🍅",
    layout="wide"
)

# Load model only once
@st.cache_resource
def load_model():
    return tf.keras.models.load_model(
        MODELS / "mobilenetv2_best.keras"
    )


@st.cache_data
def load_classes():
    df = pd.read_csv(RESULTS / "class_names.csv")
    return df["class_name"].tolist()


model = load_model()
class_names = load_classes()

# Sidebar
st.sidebar.title("🍅 Tomato Leaf AI")

page = st.sidebar.radio(
    "Navigation",
    [
        "Disease Prediction",
        "Model Comparison",
        "Training Performance",
        "Confusion Matrices"
    ]
)

st.sidebar.markdown("---")
st.sidebar.write("DSA4050 Deep Learning Project")
st.sidebar.write("Dataset: PlantVillage Tomato Leaves")
st.sidebar.write("Classes: 10")
st.sidebar.write("Best model: MobileNetV2")

# Page 1: Disease prediction
if page == "Disease Prediction":

    st.title("🍅 Tomato Leaf Disease Detection")
    st.write(
        "Upload a tomato leaf image to identify its "
        "predicted disease using MobileNetV2."
    )

    uploaded_file = st.file_uploader(
        "Choose a tomato leaf image",
        type=["jpg", "jpeg", "png"]
    )

    if uploaded_file is not None:

        image = Image.open(uploaded_file).convert("RGB")

        col1, col2 = st.columns(2)

        with col1:
            st.image(
                image,
                caption="Uploaded Tomato Leaf",
                use_container_width=True
            )

        # Preprocessing matches MobileNetV2 training
        resized = image.resize((224, 224))
        image_array = np.array(resized, dtype=np.float32)
        image_array = np.expand_dims(image_array, axis=0)

        probabilities = model.predict(image_array, verbose=0)[0]

        predicted_index = int(np.argmax(probabilities))
        predicted_class = class_names[predicted_index]
        confidence = float(probabilities[predicted_index])

        disease_name = predicted_class.replace(
            "Tomato___", ""
        ).replace("_", " ")

        with col2:
            st.subheader("Prediction Result")
            st.success(f"Predicted Class: {disease_name}")
            st.metric(
                "Model Confidence",
                f"{confidence * 100:.2f}%"
            )

            if confidence < 0.60:
                st.warning(
                    "Low-confidence prediction. "
                    "Consider using a clearer leaf image."
                )

        # Top predictions
        prediction_df = pd.DataFrame({
            "Disease": [
                name.replace("Tomato___", "").replace("_", " ")
                for name in class_names
            ],
            "Probability": probabilities * 100
        }).sort_values("Probability", ascending=False)

        st.subheader("Prediction Confidence by Class")

        fig = px.bar(
            prediction_df,
            x="Probability",
            y="Disease",
            orientation="h",
            title="Class Prediction Probabilities (%)"
        )
        fig.update_layout(yaxis={"categoryorder": "total ascending"})
        st.plotly_chart(fig, use_container_width=True)

        st.caption(
            "Predictions are generated by a model trained on "
            "PlantVillage images. Results are not a substitute "
            "for professional agricultural diagnosis."
        )

# Page 2: Model comparison
elif page == "Model Comparison":

    st.title("Model Performance Comparison")

    comparison = pd.read_csv(
        RESULTS / "model_comparison.csv"
    )

    st.dataframe(comparison, use_container_width=True)

    chart_df = comparison.melt(
        id_vars="Model",
        var_name="Metric",
        value_name="Score"
    )

    fig = px.bar(
        chart_df,
        x="Metric",
        y="Score",
        color="Model",
        barmode="group",
        title="Custom CNN vs MobileNetV2"
    )

    st.plotly_chart(fig, use_container_width=True)

    st.info(
        "MobileNetV2 achieved approximately 89.65% "
        "test accuracy, outperforming the custom CNN."
    )

# Page 3: Training performance
elif page == "Training Performance":

    st.title("Training Performance")

    selected_model = st.selectbox(
        "Select Model",
        ["Custom CNN", "MobileNetV2"]
    )

    filename = (
        "custom_cnn_history.csv"
        if selected_model == "Custom CNN"
        else "mobilenetv2_history.csv"
    )

    history = pd.read_csv(RESULTS / filename)
    history["epoch"] = history["epoch"] + 1

    col1, col2 = st.columns(2)

    with col1:
        fig = px.line(
            history,
            x="epoch",
            y=["accuracy", "val_accuracy"],
            title=f"{selected_model} Accuracy"
        )
        st.plotly_chart(fig, use_container_width=True)

    with col2:
        fig = px.line(
            history,
            x="epoch",
            y=["loss", "val_loss"],
            title=f"{selected_model} Loss"
        )
        st.plotly_chart(fig, use_container_width=True)

    st.dataframe(history, use_container_width=True)

# Page 4: Confusion matrices
elif page == "Confusion Matrices":

    st.title("Confusion Matrix Analysis")

    selected_model = st.selectbox(
        "Select Model",
        ["Custom CNN", "MobileNetV2"]
    )

    filename = (
        "Custom_CNN_confusion_matrix.png"
        if selected_model == "Custom CNN"
        else "MobileNetV2_confusion_matrix.png"
    )

    st.image(
        str(RESULTS / filename),
        caption=f"{selected_model} Confusion Matrix",
        use_container_width=True
    )

    st.write(
        "The confusion matrix shows correct predictions "
        "along the diagonal and misclassifications elsewhere."
    )
